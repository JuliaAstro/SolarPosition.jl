# Every UTC instant sits on the 84.375 s grid: its offset from noon is a multiple of
# 84375 ms, the odd factor of 86_400_000 ms. The full Julian Date of such an instant
# is exactly representable in Float64, so the solposx reference values carry no
# time-base quantization artifact. The tables below are solposx's exact Float64
# outputs with full round-trip digits, which lets the tests compare at atol = 1e-10.
