# Compare every condition against the expected true and apparent angles. The default
# refraction for Michalsky is the MICHALSKY model, so the result carries apparent angles.
function check_michalsky(alg, df_expected)
    conds = test_conditions()
    @test size(df_expected) == (19, 5)
    for ((dt, lat, lon, alt), row) in zip(eachrow(conds), eachrow(df_expected))
        obs = ismissing(alt) ? Observer(lat, lon) : Observer(lat, lon; altitude = alt)
        res = solar_position(obs, dt, alg)
        @test res isa ApparentSolPos
        @test res.elevation ≈ row.elevation atol = 1.0e-10
        @test res.apparent_elevation ≈ row.apparent_elevation atol = 1.0e-10
        @test res.zenith ≈ row.zenith atol = 1.0e-10
        @test res.apparent_zenith ≈ row.apparent_zenith atol = 1.0e-10
        @test res.azimuth ≈ row.azimuth atol = 1.0e-10
    end
    return nothing
end

@testset "Michalsky" begin
    @testset "Original Julian date" begin
        check_michalsky(Michalsky(), expected_michalsky_original_julian())
    end

    @testset "Standard Julian date" begin
        check_michalsky(
            Michalsky(julian_date = :standard), expected_michalsky_pandas_julian(),
        )
    end

    @testset "Spencer correction disabled" begin
        check_michalsky(
            Michalsky(spencer_correction = false), expected_michalsky_spencer_false(),
        )
    end

    # The original quadrant assignment adds a full turn once the sun is below the critical
    # elevation after solar noon. None of the shared conditions reaches that branch, so
    # these two evening cases cover it in both hemispheres. Both sit on the 84.375 s grid.
    @testset "Original quadrant below the critical elevation" begin
        dt = DateTime(2020, 10, 17, 20, 3, 45)
        expected = [
            45.0 => [
                -37.466479970035735, -36.90647997003573, 127.46647997003573,
                126.90647997003573, 297.89774644810706,
            ],
            -45.0 => [
                -21.800298915084763, -21.240298915084765, 111.80029891508477,
                111.24029891508476, 310.93110357433807,
            ],
        ]
        for (lat, (el, app_el, zen, app_zen, az)) in expected
            res = solar_position(
                Observer(lat, 10.0), dt, Michalsky(spencer_correction = false),
            )
            @test res.elevation ≈ el atol = 1.0e-10
            @test res.apparent_elevation ≈ app_el atol = 1.0e-10
            @test res.zenith ≈ zen atol = 1.0e-10
            @test res.apparent_zenith ≈ app_zen atol = 1.0e-10
            @test res.azimuth ≈ az atol = 1.0e-10
        end
    end

    @testset "Constructor" begin
        @test Michalsky() == Michalsky(true, :original)
        @test Michalsky(spencer_correction = false).spencer_correction === false
        @test Michalsky(julian_date = :standard).julian_date === :standard
        @test_throws ArgumentError Michalsky(julian_date = :bogus)
        # the two Julian date variants agree inside the 1950 to 2050 window
        obs = Observer(45.0, 10.0)
        dt = DateTime(2020, 10, 17, 13, 30)
        @test solar_position(obs, dt, Michalsky()) ==
            solar_position(obs, dt, Michalsky(julian_date = :standard))
    end
end
